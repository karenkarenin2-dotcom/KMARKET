# 600 дешёвых штук исчезли за 24 минуты, пол 12.00 → 16.98). Против
# аддонов, видящих прилавок живьём, мы структурно медленные.
#
# Позиционная сделка от скорости не зависит вовсе. Держишь реагент две
# недели через старт сезона — часовой лаг снимка меньше погрешности. И
# опирается она на самый сильный сигнал, какой в проекте измерен: фазу
# события, размах 30% против 11% у перцентилей и 8% у недельной сезонности.
# --------------------------------------------------------------------------

# За сколько дней до события имеет смысл набирать запас. Меньше недели —
# уже поздно: рынок к этому моменту разогрет, и мы покупаем на пике.
STOCKPILE_HORIZON_DAYS = 30

# ПОЧЕМУ ЗДЕСЬ БОЛЬШЕ НЕТ НИ БЮДЖЕТА, НИ ДОЛИ РЫНКА (решение Карена
# 2026-08-09). Сначала размер запаса считался по банку, потом к нему
# добавился предел «не больше десятой части выставленного» — первый прогон
# иначе предлагал взять 625 тысяч единиц «Сребролистной нити».
#
# Но проблема была не в пределе, а в самой попытке назвать количество.
# Карен: «меня сбивает с толку наше ограничение в 50 000, прогнозы всё
# равно нереальны, товара по факту оказывается больше, чем мы видим». И он
# прав по данным: количество в снимке дрейфует на 19.8% за час (у 23%
# товаров — больше 50%), а на «Искаженной ведунице» разошлось втрое. Цена
# при том же сравнении дрейфует на 0.3%.
#
# Значит запас отвечает на два вопроса, оба надёжные: ЧТО нужно крафту и
# ДЁШЕВО ЛИ оно сейчас. Сколько брать — видно на живом прилавке.


def _roles(data: dict) -> dict[int, dict]:
    """Роль каждого предмета в крафте: {id: {recipes, total_qty, ...}}.

    ДВА ИСТОЧНИКА, И ВТОРОЙ НЕЛЬЗЯ ЗАБЫВАТЬ. `reagents` — фиксированная
    часть состава; `slot_reagents` — то, что кладут в слоты качества, а
    там лежит основное сырьё 566 рецептов из 586. Первая версия смотрела
    только в `reagents`, и «Сумрачный сплав» из 49 рецептов в список
    запаса не попадал вовсе, хотя в слежку его уже добавили.
    """
    roles: dict[int, dict] = {}
    for key, value in (data.get("reagents") or {}).items():
        roles[int(key)] = dict(value)
    for name, entry in (data.get("slot_reagents") or {}).items():
        item_id = entry.get("id")
        if not item_id:
            continue  # это описание слота, а не предмет
        row = roles.setdefault(
            int(item_id),
            {"name": name, "recipes": 0, "total_qty": 0, "professions": []},
        )
        # Слотовые вхождения складываем с фиксированными: для вопроса
        # «насколько предмет нужен дополнению» это одно и то же.
        row["recipes"] = row.get("recipes", 0) + int(entry.get("recipes") or 0)
        row.setdefault("name", name)
        row["from_slots"] = True
    return roles


def stockpile(
    views: list[ItemView],
    *,
    now: pd.Timestamp | None = None,
    limit: int = 15,
) -> dict:
    """Что набирать сейчас, чтобы продать в спрос на старте контента.

    НАПРАВЛЕНИЕ У РЕАГЕНТОВ НЕ ТАКОЕ, КАК У ЖЕТОНА, и это важно. Жетон
    Карен покупает за золото, поэтому «дорого перед патчем» для него плохая
    новость. Реагенты ПОТРЕБЛЯЮТ, и потребление привязано к контенту: к
    старту сезона все разом садятся крафтить снаряжение, чары и расходники.
    Значит набирать надо ДО, а продавать в спрос ПОСЛЕ старта.

    ЧЕСТНО О ТОМ, ЧЕГО МЫ НЕ ЗНАЕМ. Величина эффекта на реагентах у нас НЕ
    ИЗМЕРЕНА: +12%/−11.8% получены на жетоне, а по commodities истории
    вообще ни у кого нет — мы записываем первый в жизни цикл прямо сейчас.
    Поэтому модуль называет роль и цену (это факты), а про размер движения
    молчит. Выдуманная точность на деньгах опаснее отсутствия ответа.
    """
    from .. import recipes  # локально: аналитика не должна тянуть сбор рецептов

    roles = _roles(recipes.load() or {})
    event = events.context(now=now)
    upcoming = events.upcoming(2)

    rows: list[dict] = []
    for view in views:
        role = roles.get(view.item_id)
        if not role:
            continue  # не реагент текущего дополнения — не наша тема
        if not view.floor_gold:
            continue

        rows.append(
            {
                "item_id": view.item_id,
                # Имя из рецептов — запасной вариант для реагентов, которые
                # попали в слежку по роли и в справочник ещё не занесены.
                # Без него в списке стоят «Предмет 243060», и человек не
                # понимает, что ему предлагают купить.
                "name": view.name
                if not view.name.startswith("Предмет ")
                else (role.get("name") or view.name),
                "icon": view.icon,
                "recipes": role.get("recipes", 0),
                "total_qty": role.get("total_qty", 0),
                "professions": role.get("professions", []),
                "floor_gold": view.floor_gold,
                "market_gold": view.market_gold,
                # КОЛИЧЕСТВ ЗДЕСЬ НЕТ НАМЕРЕННО (решение Карена 2026-08-09).
                # Количество — самая недостоверная величина в наших данных:
                # медианный дрейф между часовыми снимками 19.8%, у 23%
                # товаров больше 50%, а на «Искаженной ведунице» разошлось
                # втрое (4 069 в снимке против 12 748 в игре). Цена при том
                # же сравнении дрейфует на 0.3%.
                #
                # Строить главный экран на самом шатком числе — значит
                # выдавать догадку за расчёт. Сколько брать, человек видит
                # на живом прилавке; наше дело — сказать, ЧТО нужно и
                # дёшево ли оно сейчас.
                "percentile": view.percentile,
                "points": view.points,
                "change_pct": view.change_pct,
                "current_era": view.current_era,
            }
        )

    # ПОРЯДОК: сначала нужность, потом дешевизна. Роль — факт из рецептов,
    # цена — то, что мы пока едва измерили; нельзя, чтобы шум в двухдневной
    # истории перебивал знание о том, что предмет вообще нужен.
    def rank(row: dict) -> tuple:
        cheap = row["percentile"] if row["percentile"] is not None else 50.0
        return (-(row["recipes"] * (100 - cheap)), -row["recipes"])

    rows.sort(key=rank)

    return {
        "event": event,
        "upcoming": upcoming,
        "horizon_days": STOCKPILE_HORIZON_DAYS,
        "candidates": rows[:limit],
        "tracked": len(rows),
        # Отдельным полем, чтобы интерфейс не забыл сказать это вслух.
        "measured": False,
        "note": (
            "Размер движения цен на реагентах у нас НЕ измерен: по товарному "
            "аукциону истории не существует ни у кого, и этот цикл патча мы "
            "записываем первым. Роль в крафте и цена — факты, ожидаемый рост — "
            "пока гипотеза, которую этот же цикл и проверит."
        ),
    }


def craft_margin(
    quotes: dict, *, limit: int = 15, budget_gold: float = BUDGET_GOLD
) -> dict:
    """Что выгодно скрафтить: сырьё дешевле изделия.

    ПОЧЕМУ ЭТО НЕ ЗАВИСИТ ОТ НАШЕЙ МЕДЛЕННОСТИ. Выкуп дешёвого хвоста
    требует успеть раньше других — там мы структурно проигрываем (снимок
    часовой, хвост живёт минуты). Крафт-маржа живёт иначе: это разница
    между двумя РЫНКАМИ, сырья и изделия, и она держится часами и днями,
    потому что её закрывает не один быстрый покупатель, а производство.

    СЧИТАЕТСЯ ДАЛЕКО НЕ ВСЁ, и это ограничение API, а не наша лень.

    1. РЕЦЕПТЫ СО СЛОТАМИ КАЧЕСТВА ВЫБРАСЫВАЮТСЯ ЦЕЛИКОМ — 566 из 586.
       В `reagents` лежит лишь фиксированная часть сырья, остальное игрок
       кладёт в слоты, а слот несёт ТОЛЬКО имя реагента, без количества
       (проверено на «Поющей шестеренке»: видимого сырья 1 каркас, плюс
       три слота без чисел). Сколько руды уходит в изделие, API не
       сообщает нигде.

       ПОЧЕМУ ВЫБРАСЫВАЕМ, А НЕ ПОМЕЧАЕМ. Сначала такие рецепты просто
       несли флаг «сырьё неполное». Первый же прогон показал, что этого
       мало: метрика systematically поднимает наверх рецепты с САМОЙ
       БОЛЬШОЙ дырой в себестоимости. «Подкладка из тайной ткани» вышла
       первой с наваром 407 МИЛЛИОНОВ золота — просто потому, что из трёх
       слотов не посчитан ни один, а видимого сырья там на 0.07 з. Флаг
       рядом с таким числом не спасает: чем неполнее данные, тем выше
       строка. Это тот же класс ошибки, что «навар от выкупа всего
       хвоста», — метрика оптимизирует артефакт вместо выгоды.

    2. СНАРЯЖЕНИЕ НЕ ПОПАДАЕТ ВОВСЕ: оно торгуется на реалмовых
       аукционах, которых мы не собираем.

    Остаётся немного — приманки, наживки и подобное, — но там числа
    настоящие.
    """
    from .. import recipes

    data = recipes.load()
    reagents = data.get("reagents") or {}
    rows: list[dict] = []

    # Стоимость единицы сырья берём по УРОВНЮ ВОССТАНОВЛЕНИЯ, а не по полу:
    # закупая сырьё мешками, ты выметаешь дешёвые лоты и платишь примерно
    # по нему. Пол здесь польстил бы ровно так же, как «цена после» льстила
    # в расчёте перекупки.
    def unit_cost(item_id: int) -> int | None:
        quote = quotes.get(item_id)
        return quote.market if quote else None

    skipped_slots = 0
    for entry in data.get("products") or []:
        product_id = entry.get("product_id")
        if not product_id:
            continue
        if entry.get("quality_slots"):
            # Себестоимость посчитать нечем — см. разбор в шапке функции.
            skipped_slots += 1
            continue
        product = quotes.get(product_id)
        if not product:
            continue  # изделие не на товарном аукционе (обычно снаряжение)

        recipe_id = entry["recipe_id"]
        cost = 0
        known_all = True
        parts: list[dict] = []
        composition = entry.get("items") or []
        if not composition:
            continue
        for part in composition:
            price = unit_cost(part["id"])
            if price is None:
                known_all = False
                break
            cost += price * int(part.get("quantity") or 0)
            parts.append(
                {
                    "id": part["id"],
                    "name": part.get("name", ""),
                    "quantity": part.get("quantity"),
                    "unit_gold": _gold(price),
                }
            )
        if not known_all or cost <= 0:
            continue

        revenue = product.market * (1 - AH_FEE)
        profit = (revenue - cost) / COPPER_PER_GOLD
        if profit <= 0:
            continue
        # Размер партии ограничен не только деньгами, но и СЫРЬЁМ на
        # прилавке: рецепт, под который в продаже сотня реагентов, нельзя
        # прокрутить тысячу раз, сколько бы золота ни лежало в банке.
        runs = int(budget_gold * COPPER_PER_GOLD // cost)
        for part in composition:
            stock = quotes.get(part["id"])
            need = int(part.get("quantity") or 0)
            if stock and need:
                runs = min(runs, stock.quantity // need)
        if runs <= 0:
            continue
        rows.append(
            {
                "recipe_id": recipe_id,
                "name": entry.get("product_name") or entry.get("name"),
                "profession": entry.get("profession"),
                "cost_gold": _gold(cost),
                "price_gold": _gold(product.market),
                "profit_gold": round(profit, 2),
                "roi_pct": round(profit / (cost / COPPER_PER_GOLD) * 100, 1),
                "runs_on_budget": runs,
                "batch_profit_gold": round(profit * runs, 0),
                "partial": bool(entry.get("quality_slots")),
                "quality_slots": entry.get("quality_slots", 0),
                "reagents": parts,
            }
        )

    rows.sort(key=lambda r: -r["batch_profit_gold"])
    return {
        "candidates": rows[:limit],
        "total": len(rows),
        "skipped_slots": skipped_slots,
        "budget_gold": budget_gold,
        "note": (
            f"Посчитаны только рецепты, у которых известно ВСЁ сырьё. "
            f"Ещё {skipped_slots} рецептов пропущено: у них есть слоты качества, "
            f"а Blizzard сообщает лишь ЧТО туда кладут, не сколько — посчитать "
            f"себестоимость нечем. Снаряжение не попадает вовсе: оно торгуется "
            f"на реалмовых аукционах, которых мы не собираем."
        ),
    }


def readiness(views: list[ItemView]) -> dict:
    """Что уже созрело, а что ещё копится.

    Нужно, чтобы человеку НЕ ПРИХОДИЛОСЬ СПРАШИВАТЬ, заработала ли
    скорость товара. Сборщик наполняет историю сам, и приложение обязано
    само сказать, когда её стало достаточно.
    """
    if not views:
        return {"points": 0, "activity": 0, "levels": 0, "total": 0}
    points = max(v.points for v in views)
    return {
        "points": points,
        "activity": sum(1 for v in views if v.activity_pct is not None),
        "sold": sum(1 for v in views if v.sold_per_hour is not None),
        # Приток — вторая половина скорости. Пока он не измерен, размер
        # сделки считается по одному кошельку, и об этом надо говорить.
        "restock": sum(1 for v in views if v.restock_per_hour is not None),
        "planned": sum(1 for v in views if v.net_per_hour is not None),
        "levels": sum(1 for v in views if v.percentile is not None),
        "total": len(views),
        "need_activity": MIN_POINTS_ACTIVITY,
        "need_sold": MIN_POINTS_SOLD,
        "need_levels": MIN_POINTS,
        "budget_gold": BUDGET_GOLD,
        "horizon_hours": HORIZON_HOURS,
    }


def summary(region: str = config.PRIMARY_REGION, *, live: dict | None = None) -> dict:
    """Готовый к показу срез аукциона."""
    views = board(region, live=live)
    event = events.context()
    stored = watchlist.load()
    return {
        "readiness": readiness(views),
        "rhythm": rhythm(region),
        "region": region,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "watchlist_generated": stored.get("generated_utc"),
        "window_days": WINDOW_DAYS,
        "tracked": len(views),
        "event": event,
        "items": [asdict(v) for v in views],
        # Запас под цикл патча идёт ПЕРЕД находками: после разворота
        # 2026-08-09 это главный ответ модуля, а выкуп дешёвого хвоста —
        # лотерея, в которой мы структурно медленные.
        "stockpile": stockpile(views),
        # Крафт считается ТОЛЬКО по живому снимку: там есть цены всех 12
        # тысяч предметов, а в узкой истории — лишь по списку слежки, и
        # половина сырья с изделиями в неё не входит. Без цен обеих сторон
        # маржа не считается, и подсовывать вместо неё оценку нельзя.
        "craft": craft_margin(live) if live else None,
        "bargains": [asdict(v) for v in bargains(views)],
    }
