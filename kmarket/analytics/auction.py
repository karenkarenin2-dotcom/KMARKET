def _activity(history: pd.DataFrame) -> float | None:
    """Насколько живо шевелится запас товара, % от запаса за снимок.

    ЧТО ЭТО ЧЕСТНО МЕРЯЕТ, А ЧТО НЕТ. Мы храним только свёртку стакана, а
    не отдельные лоты, поэтому отличить «продали 100 штук» от «выставили
    100 штук» невозможно: в обе стороны меняется одно и то же число.
    Значит «объём продаж» отсюда не получить, и делать вид, что получили,
    нельзя.

    Зато прекрасно видно ДРУГОЕ: шевелится рынок вообще или стоит. Если
    запас скачет от снимка к снимку — товар живой, его и покупают, и
    доставляют. Если из часа в час лежит одно и то же число, значит лоты
    просто висят, и выкупленный дешёвый хвост будет висеть точно так же.

    Ровно на этот вопрос и нужен ответ, когда решаешь, выкупать ли
    находку: не «сколько продадут», а «продадут ли вообще».

    Берём МЕДИАНУ модуля изменения, а не среднее: одна поставка на
    полмиллиона единиц иначе объявила бы мёртвый рынок живым.
    """
    if len(history) < MIN_POINTS_ACTIVITY:
        return None
    quantity = history["quantity"].astype(float)
    typical = float(quantity.median())
    if not typical:
        return None
    step = quantity.diff().abs().dropna()
    if step.empty:
        return None
    return round(float(step.median()) / typical * 100, 1)


def _sold_rate(history: pd.DataFrame) -> float | None:
    """Сколько единиц уходит с прилавка в час. None — если не измеряли.

    Считается по строкам, где сборщик застал оба соседних снимка и смог
    сравнить лоты. Медиана, а не среднее: один всплеск спроса не должен
    объявлять товар ходовым навсегда.

    ВЕРХНЯЯ ОЦЕНКА, НЕ ТОЧНОЕ ЧИСЛО. Снятие лота продавцом (чтобы
    перевыставить дешевле) снаружи неотличимо от покупки, а подрезают
    друг друга постоянно. Значит настоящие продажи не больше этого числа,
    но могут быть заметно меньше. Для сравнения товаров между собой
    годится, для обещаний по срокам — только с оговоркой.
    """
    if history.empty or "sold_qty" not in history:
        return None
    rows = history.dropna(subset=["sold_qty", "sold_hours"])
    rows = rows[rows["sold_hours"] > 0]
    if len(rows) < MIN_POINTS_SOLD:
        return None
    per_hour = rows["sold_qty"].astype(float) / rows["sold_hours"].astype(float)
    return round(float(per_hour.median()), 1)


def _restock_rate(history: pd.DataFrame) -> float | None:
    """Сколько ДЕШЁВЫХ единиц подвозят на прилавок в час. None — не измеряли.

    Зеркало _sold_rate и меряется тем же сравнением лотов, только в другую
    сторону: сколько новых лотов встало НИЖЕ уровня восстановления.

    ЗАЧЕМ ОТДЕЛЬНО ОТ ПРОДАЖ. Продажи говорят, что товар уходит; они не
    говорят, достанется ли выручка тебе. Перекупщик живёт на разнице между
    тем, как быстро разбирают, и тем, как быстро подвозят новое дешёвое.
    Если подвозят быстрее — очередь перед тобой не рассасывается никогда,
    сколько бы ни продавалось: снизу постоянно встаёт кто-то ещё дешевле,
    и приходится снимать и перевыставлять. Именно это Карен и описал,
    попробовав торговать по нашим находкам.
    """
    if history.empty or "added_qty" not in history:
        return None
    rows = history.dropna(subset=["added_qty", "sold_hours"])
    rows = rows[rows["sold_hours"] > 0]
    if len(rows) < MIN_POINTS_SOLD:
        return None
    per_hour = rows["added_qty"].astype(float) / rows["sold_hours"].astype(float)
    return round(float(per_hour.median()), 1)


def _stops(
    book: tuple[tuple[int, int], ...] | list[tuple[int, int]],
    market: int,
    budget_copper: float,
) -> list[tuple[int, int, int, int]]:
    """Все точки остановки выкупа: (цена продажи, стена, количество, затраты).

    ГЛАВНАЯ МЫСЛЬ, ОПЛАЧЕННАЯ ОШИБКОЙ 2026-08-09. Перепродать можно не по
    той цене, которую ты назначил, а по той, до которой ДОТЯНУЛСЯ выкуп.
    Купив половину дешёвых лотов, ты не поднял пол: под тобой остались
    чужие, и покупатели уйдут к ним.

    Карен показал это скриншотом из игры. У «Рысевки» пол стоял на 21.97 з,
    наша «цена после» — на 37.42 з, но чтобы пол реально дошёл до 37.42,
    надо было выкупить 14 886 шт за 381 тысячу. На бюджет в 50 тысяч
    берётся ~2 250 шт, и новый пол оказывается 22.19 з — то есть вся
    затея приносит минус после комиссии.

    Поэтому перебираем ГРАНИЦЫ ступенек: остановившись перед ступенькой,
    ты выкупил всё, что дешевле неё, и новый пол равен её цене. Продавать
    придётся по ней, встав в очередь к тем, кто на ней уже стоит.

    Частичный выкуп ступеньки смысла не имеет: пол остаётся на её же цене,
    а купленные по ней единицы приносят минус комиссию. Поэтому точки
    остановки — ровно границы, и их немного (медиана 6 на товар).
    """
    stops: list[tuple[int, int, int, int]] = []
    qty = cost = 0
    for price, available in book:
        # Остановка ПЕРЕД этой ступенькой: всё, что дешевле, уже куплено,
        # и новый пол равен её цене.
        if qty and cost <= budget_copper:
            stops.append((price, int(available), qty, cost))
        if price <= 0:
            continue
        qty += int(available)
        cost += price * int(available)
        if cost > budget_copper:
            break
    # Выкуплен ВЕСЬ дешёвый хвост — тогда пол поднимается до уровня
    # восстановления, и это единственный случай, когда продажа идёт по
    # market. Ровно на нём держалась прежняя формула, и в нём она была
    # верна; неверным было распространять её на частичный выкуп.
    if qty and cost <= budget_copper:
        stops.append((market, 0, qty, cost))
    return stops


def _gap_rate(history: pd.DataFrame) -> float | None:
    """Как ЧАСТО у товара вообще бывает разрыв, достойный выкупа, в %.

    ПОЧЕМУ ЭТО ВАЖНЕЕ РАЗМЕРА НАВАРА. Снимок Blizzard обновляется раз в
    час, и точное количество дешёвых лотов к моменту покупки уже другое
    (замерено: дрейф 19.8%). Значит гнаться за конкретным лотом мы не
    можем — мы структурно медленные, и это не чинится.

    Зато можно ответить на другой вопрос, который от скорости не зависит:
    у ЭТОГО товара скидка — постоянное свойство рынка или разовая
    случайность? Замер по 32 снимкам показал, что разница огромная: у
    товаров текущего дополнения разрыв держится у 12 позиций больше
    половины времени, а у остальных 146 мелькает изредка.

    Первые — маршрут, по которому имеет смысл ходить регулярно. Вторые —
    лотерея, в которой мы заведомо проигрываем более быстрым.
    """
    if history.empty or len(history) < MIN_POINTS_ACTIVITY:
        return None
    rows = history.dropna(subset=["deal_qty", "deal_cost"])
    if rows.empty:
        return None
    # ТОЛЬКО ТЕ СНИМКИ, ГДЕ ХВОСТ БЫЛ ПО КАРМАНУ. В истории ступенек нет —
    # там лежат лишь итоги по хвосту, — поэтому единственный случай, в
    # котором прежняя формула честна, это выкуп хвоста ЦЕЛИКОМ: тогда пол
    # действительно поднимается до уровня восстановления. Когда хвост
    # дороже банка, та же формула обещает цену, до которой выкуп не
    # дотянется (см. _stops и разбор «Рысевки»), и снимок в счёт не идёт.
    rows = rows[rows["deal_cost"] <= BUDGET_GOLD * COPPER_PER_GOLD]
    if rows.empty:
        return 0.0
    upside = (
        rows["deal_qty"] * rows["market"] * (1 - AH_FEE) - rows["deal_cost"]
    ) / COPPER_PER_GOLD
    cost = rows["deal_cost"] / COPPER_PER_GOLD
    roi = (upside / cost.replace(0, pd.NA)) * 100
    worthy = (upside >= MIN_UPSIDE_GOLD) & (roi >= MIN_ROI_PCT)
    # Доля от ВСЕХ снимков, а не от подходящих по бюджету: вопрос стоит
    # «как часто сюда имеет смысл заходить», и снимки, где хвост был
    # неподъёмным, — это тоже «не имеет смысла».
    return round(float(worthy.sum()) / len(history) * 100, 0)


def _plan(
    view: ItemView,
    book: tuple[tuple[int, int], ...],
    market: int,
    budget_gold: float = BUDGET_GOLD,
    horizon: float = HORIZON_HOURS,
) -> None:
    """Посчитать СДЕЛКУ: сколько взять, во что встанет, что принесёт.

    Три предела, и сделка равна самому узкому из них:

    1. КОШЕЛЁК. Из хвоста берём самое дешёвое, пока хватает бюджета.
    2. СБЫТ. За горизонт очередь освобождается на `net × horizon` единиц, и
       первыми уходят те, кто уже стоит по цене перепродажи. Что осталось
       сверх стены — и есть место для нас.
    3. НАЛИЧИЕ. Больше, чем лежит в хвосте, купить нельзя.

    ПОЧЕМУ ВЫЧИТАЕТСЯ ИМЕННО СТЕНА, А НЕ НАШ ОБЪЁМ. Перевыставив купленное,
    ты встаёшь ЗА теми, кто уже стоит по этой цене, — это Карен проверил
    золотом на «Сущности маназмея»: выкупил хвост в 25 тысяч, впереди
    стояло 210 тысяч, продал девятнадцать штук.

    И ПОЧЕМУ СКОРОСТЬ БЕРЁТСЯ ЧИСТАЯ. Продажи минус подвоз нового дешёвого.
    Товар, куда каждый час доливают дешёвого больше, чем разбирают, — не
    сделка ни при какой марже: тебя будут подрезать ровно столько, сколько
    ты готов ждать.
    """
    if not book:
        view.plan_limit = "дешёвого хвоста нет"
        return

    budget_copper = budget_gold * COPPER_PER_GOLD
    stops = _stops(book, market, budget_copper)
    if not stops:
        банк = f"{budget_gold:,.0f}".replace(",", " ")
        view.plan_limit = f"на {банк} з не выкупить даже нижнюю ступеньку"
        return

    if view.net_per_hour is not None and view.net_per_hour <= 0:
        view.plan_limit = "дешёвого подвозят не меньше, чем разбирают"
        return

    best = None
    for price, wall, qty, cost in stops:
        # Стена на уровне market живёт в снимке отдельно: это те, кто уже
        # стоит по цене восстановления.
        if price == market and not wall:
            wall = view.wall_qty
        profit = (qty * price * (1 - AH_FEE) - cost) / COPPER_PER_GOLD
        if profit <= 0:
            continue
        # Пока ёмкость уровня не измерена скоростью, судим по глубине
        # стакана: вываливать втрое больше того, что там стоит, —
        # значит самому стать дешёвым хвостом (см. MAX_OVERHANG).
        if view.net_per_hour is None and qty > max(wall, 1) * MAX_OVERHANG:
            continue
        hours = None
        if view.net_per_hour:
            hours = round((wall + qty) / view.net_per_hour, 1)
            if hours > MAX_HOURS_TO_CLEAR:
                continue  # деньги застрянут дольше недели — это не сделка
            per_hour = profit / max(hours, 1.0)
        else:
            per_hour = profit / horizon
        if best is None or per_hour > best[0]:
            best = (per_hour, price, wall, qty, cost, profit, hours)

    if best is None:
        # Разрыв в стакане есть, а денег в нём нет: на доступный бюджет
        # пол сдвигается на копейки, и комиссия съедает остаток. Именно
        # так выглядит «огромный дешёвый хвост» изнутри.
        view.plan_limit = "на этот бюджет пол почти не сдвинется"
        return

    per_hour, price, wall, qty, cost, profit, hours = best
    view.plan_qty = qty
    view.plan_cost_gold = round(cost / COPPER_PER_GOLD, 0)
    view.plan_profit_gold = round(profit, 0)
    view.plan_sell_gold = round(price / COPPER_PER_GOLD, 2)
    view.plan_roi_pct = (
        round(view.plan_profit_gold / view.plan_cost_gold * 100, 1)
        if view.plan_cost_gold
        else 0.0
    )
    view.plan_hours = hours
    # Прибыль в час — по СРОКУ СДЕЛКИ, а не по горизонту: сделка,
    # обернувшаяся за три часа, лучше такой же за двадцать четыре, и
    # деление на общий горизонт эту разницу стёрло бы.
    view.plan_profit_per_hour = round(per_hour, 0)
    # Очередь на уровне продажи — та, за которой ты встанешь. Это не та же
    # стена, что в снимке: она считается для ТВОЕЙ цены выхода.
    view.wall_qty = wall
    view.plan_limit = "весь хвост" if price == market else "до следующей ступеньки"


def _percentile(series: pd.Series, current: float) -> float:
    """Доля моментов, когда было ДЕШЕВЛЕ текущего. 0 — исторический минимум."""
    if series.empty:
        return 50.0
    return round(float((series < current).mean()) * 100, 1)


def _describe(view: ItemView, event: dict | None) -> None:
    """Проставить состояние и причины. Причины обязательны — см. verdict.py."""
    reasons: list[str] = []

    if view.plan_profit_gold >= MIN_UPSIDE_GOLD and view.plan_roi_pct >= MIN_ROI_PCT:
        qty = f"{view.plan_qty:,}".replace(",", " ")
        cost = f"{view.plan_cost_gold:,.0f}".replace(",", " ")
        gain = f"{view.plan_profit_gold:,.0f}".replace(",", " ")
        срок = ""
        if view.plan_hours is not None:
            срок = (
                f" примерно за {view.plan_hours:.0f} ч"
                if view.plan_hours < 48
                else f" примерно за {view.plan_hours / 24:.1f} сут"
            )
        reasons.append(
            f"СДЕЛКА: выкупить всё дешевле {view.plan_sell_gold} з — это {qty} шт "
            f"за {cost} з, — и перевыставить по {view.plan_sell_gold} з. "
            f"Чистыми около {gain} з{срок}."
        )

        # ПОЧЕМУ ИМЕННО ДО ЭТОЙ ЦЕНЫ. Без этой строки человек видит в игре
        # лоты дешевле «цены после» и не понимает, отчего софт остановился
        # раньше. Ответ: дальше не хватает бюджета, а недовыкупленный
        # хвост держит пол внизу — продать по «цене после» будет нельзя.
        if view.plan_limit == "до следующей ступеньки":
            лежит = f"{view.deal_qty:,}".replace(",", " ")
            банк = f"{BUDGET_GOLD:,.0f}".replace(",", " ")
            reasons.append(
                f"Выше по стакану ещё {лежит} шт дешевле уровня восстановления "
                f"({view.market_gold} з), но выкупить их все банк в {банк} з не "
                f"позволяет. А пока они лежат, пол выше {view.plan_sell_gold} з "
                f"не поднимется — продавать придётся по ней."
            )

        # Скорость: сначала прямая (продажи минус подвоз), потом косвенная.
        if view.net_per_hour is not None:
            подвоз = (
                f", подвозят {view.restock_per_hour:.0f} шт/ч"
                if view.restock_per_hour
                else ", подвоза дешёвого почти нет"
            )
            wall = f"{view.wall_qty:,}".replace(",", " ")
            reasons.append(
                f"Разбирают {view.sold_per_hour:.0f} шт/ч{подвоз} — очередь тает на "
                f"{view.net_per_hour:.0f} шт/ч. По цене перепродажи впереди тебя "
                f"стоит {wall} шт."
            )
            reasons.append(
                "И это оптимистично: скорость измерена, пока товар стоил дёшево. "
                "По цене выше спрос обычно падает — проверено на «Сущности "
                "маназмея», где после выкупа хвоста продажи почти встали."
            )
        elif view.activity_pct is None:
            reasons.append(
                f"Скорость ещё не измерена (нужно {MIN_POINTS_SOLD} измерений) — "
                f"размер сделки посчитан по одному кошельку, а не по сбыту. "
                f"На залежалом товаре хвост можно выкупить и остаться с ним."
            )
        elif view.activity_pct < 1.0:
            reasons.append(
                f"Запас почти не шевелится ({view.activity_pct}% за снимок) — рынок "
                f"стоячий. Выкупить хвост можно, продать будет некому."
            )
        else:
            reasons.append(
                f"Запас шевелится на {view.activity_pct}% за снимок — рынок живой."
            )
    elif view.plan_limit and view.plan_limit not in (
        "весь хвост",
        "до следующей ступеньки",
    ):
        # Почему сделки НЕТ — знание не менее полезное, чем сама находка:
        # без него человек видит жирный разрыв в стакане и не понимает,
        # отчего софт молчит.
        reasons.append(f"Сделки нет: {view.plan_limit}.")

        # Очередь перед тобой. Видна сразу, истории не требует, и именно
        # она чаще всего убивает сделку, которая по арифметике хороша.
        if view.wall_ratio and view.wall_ratio > MAX_WALL_RATIO:
            wall = f"{view.wall_qty:,}".replace(",", " ")
            reasons.append(
                f"⚠ По цене перепродажи уже стоит {wall} шт — это в "
                f"{view.wall_ratio:.0f} раз больше того, что ты купишь. "
                f"Перевыставленное встанет в конец этой очереди."
            )

        # Постоянство разрыва — главный ответ на вопрос «идти ли туда».
        if view.gap_rate is not None:
            if view.gap_rate >= 50:
                reasons.append(
                    f"Разрыв держится постоянно — он был в {view.gap_rate:.0f}% "
                    f"прошлых снимков. Сюда имеет смысл заглядывать регулярно."
                )
            else:
                reasons.append(
                    f"Разрыв разовый: за всю историю он был лишь в "
                    f"{view.gap_rate:.0f}% снимков. Пока дойдёшь, его могут разобрать."
                )

        # Старый товар с большим спредом — это почти всегда не подарок, а
        # предупреждение (замерено: 9 находок из 11 оказались старьём,
        # тогда как у текущего дополнения доходность 2.5–7.8%).
        if not view.current_era:
            reasons.append(
                "Товар не из текущего дополнения. Большой спред у такого обычно "
                "оттого, что рынок никто не смотрит, — и по той же причине "
                "перепродать бывает некому."
            )

    if view.percentile is None:
        reasons.append(
            f"Истории всего {view.points} замеров — про уровень цены сказать нечего. "
            f"Копим, перцентиль появится сам."
        )
    else:
        reasons.append(
            f"Цена в нижних {view.percentile:.0f}% своих значений за {WINDOW_DAYS} дн."
        )

    if view.supply_change_pct is not None and abs(view.supply_change_pct) >= 25:
        direction = "выросло" if view.supply_change_pct > 0 else "упало"
        reasons.append(
            f"Предложение {direction} на {abs(view.supply_change_pct):.0f}% за окно — "
            + ("рынок затоваривается." if view.supply_change_pct > 0 else "товар выметают.")
        )

    # Фаза события. Для реагентов знак обратный жетону: перед контентом
    # они дорожают, потому что все готовятся крафтить.
    #
    # БЕЗ ИСТОРИИ НАПРАВЛЕНИЕ НЕ НАЗЫВАЕМ. Фаза патча одна на весь рынок,
    # и если разрешить ей самой рождать совет, все 80 товаров разом
    # получат «продавать» — совет, который не про товар, а про календарь.
    # Поэтому фаза только СДВИГАЕТ уже имеющееся мнение, а собственное
    # мнение появляется лишь вместе с перцентилем.
    state = UNKNOWN
    if view.percentile is not None:
        if view.percentile <= 25:
            state = BUY
        elif view.percentile >= 75:
            state = SELL
        else:
            state = HOLD

    if event:
        days, phase = event["days"], event["phase"]
        if phase == "before":
            reasons.append(
                f"Через {days} дн — {event['label']}. Перед контентом реагенты и "
                f"расходники разбирают под крафт: цены обычно идут вверх, это "
                f"фаза продажи запасённого, а не набора."
            )
            if state == BUY and view.percentile is not None and view.percentile > 10:
                # Дёшево перед патчем — это ещё не «дёшево», а «пока не
                # начали разбирать». Брать можно, но без энтузиазма.
                state = HOLD
            elif state == HOLD:
                state = SELL
        elif phase == "after":
            reasons.append(
                f"{event['label']} прошло {abs(days)} дн назад — ажиотаж спал, "
                f"реагенты обычно дешевеют. Фаза набора."
            )
            if state == HOLD:
                state = BUY

    # Выкуп дешёвого хвоста перебивает перцентиль и фазу патча: это
    # арбитраж здесь и сейчас.
    #
    # НО ТОЛЬКО ЕСЛИ РЫНОК ЖИВОЙ. Ради этого и меряется движение: на
    # стоячем товаре арбитраж существует лишь на бумаге — выкупить хвост
    # можно, а продать его некому, и золото застревает в стопке реагентов.
    # Пока движение не измерено, право говорить «брать» оставляем (иначе
    # первые полсуток работы модуль молчал бы обо всём), но оговорка про
    # неизмеренную скорость уже добавлена выше.
    arbitrage = (
        view.plan_profit_gold >= MIN_UPSIDE_GOLD and view.plan_roi_pct >= MIN_ROI_PCT
    )
    # Прямое измерение бьёт косвенное: если знаем скорость продаж, судим
    # по сроку распродажи хвоста, и только иначе — по шевелению запаса.
    if view.hours_to_clear is not None:
        view.stalled = view.hours_to_clear > MAX_HOURS_TO_CLEAR
    else:
        view.stalled = view.activity_pct is not None and view.activity_pct < 1.0
    # Длинная очередь по цене перепродажи запирает деньги не хуже мёртвого
    # рынка, и видна она сразу — не дожидаясь измерения скорости.
    if view.wall_ratio and view.wall_ratio > MAX_WALL_RATIO:
        view.stalled = True
    if arbitrage and not view.stalled:
        state = BUY
    elif arbitrage and view.stalled and state == UNKNOWN:
        state = HOLD

    view.state = state
    view.reasons = reasons


def board(
    region: str = config.PRIMARY_REGION,
    *,
    live: dict | None = None,
    now: pd.Timestamp | None = None,
) -> list[ItemView]:
    """Все предметы под слежкой с показателями и советом.

    `live` — свежий снимок (dict item_id -> Quote) из auction.fetch. Если
    его нет, берём последнюю точку истории.
    """
    table = frame(region)
    event = events.context(now=now)
    watched = watchlist.item_ids()

    cutoff = (now or pd.Timestamp.now(tz="UTC")) - pd.Timedelta(days=WINDOW_DAYS)
    recent = table[table.index >= cutoff] if not table.empty else table

    views: list[ItemView] = []
    for item_id in watched:
        entry = items.get(item_id) or {}
        view = ItemView(
            item_id=item_id,
            name=entry.get("name") or f"Предмет {item_id}",
            icon=entry.get("icon", ""),
            subclass=entry.get("subclass", ""),
            quality=entry.get("quality", ""),
            rank=entry.get("rank"),
            rank_of=entry.get("rank_of"),
        )

        history = recent[recent["item_id"] == item_id] if not recent.empty else recent

        quote = (live or {}).get(item_id)
        if quote is not None:
            floor, market = quote.floor, quote.market
            quantity, lots = quote.quantity, quote.lots
            deal_qty, deal_cost = quote.deal_qty, quote.deal_cost
            wall_qty = quote.wall_qty
            book = quote.deal_book
        elif not history.empty:
            last = history.iloc[-1]
            floor, market = int(last["floor"]), int(last["market"])
            quantity, lots = int(last["quantity"]), int(last["lots"])
            deal_qty, deal_cost = int(last["deal_qty"]), int(last["deal_cost"])
            wall_qty = int(last.get("wall_qty") or 0)
            # В истории ступенек нет и быть не может — они живут только в
            # памяти снимка. Считаем хвост одной ступенькой по средней
            # цене: для несвежих данных точность стакана всё равно
            # иллюзорна, а порядок величины сохраняется.
            book = (
                ((deal_cost // deal_qty, deal_qty),) if deal_qty and deal_cost else ()
            )
        else:
            continue  # ни живого снимка, ни истории — показывать нечего

        view.floor_gold = _gold(floor)
        view.market_gold = _gold(market)
        view.quantity, view.lots = quantity, lots
        view.discount_pct = round((1 - floor / market) * 100, 1) if market else 0.0
        view.deal_qty = deal_qty
        view.deal_cost_gold = round(deal_cost / COPPER_PER_GOLD, 0)
        view.upside_gold = round(
            (deal_qty * market * (1 - AH_FEE) - deal_cost) / COPPER_PER_GOLD, 0
        )
        view.roi_pct = (
            round(view.upside_gold / view.deal_cost_gold * 100, 1)
            if view.deal_cost_gold
            else 0.0
        )
        view.points = int(len(history))
        view.current_era = item_id >= CURRENT_ERA_FROM_ID
        view.activity_pct = _activity(history)
        view.sold_per_hour = _sold_rate(history)
        view.restock_per_hour = _restock_rate(history)
        if view.sold_per_hour is not None:
            # Приток может быть ещё не измерен (поле появилось позже
            # продаж) — тогда считаем его нулевым, но это оптимизм, и в
            # объяснении он назван вслух.
            view.net_per_hour = round(
                view.sold_per_hour - (view.restock_per_hour or 0.0), 1
            )
        view.gap_rate = _gap_rate(history)
        view.wall_qty = wall_qty
        if view.net_per_hour and view.net_per_hour > 0 and view.deal_qty:
            # СЧИТАЕМ ОЧЕРЕДЬ, А НЕ СВОЙ ХВОСТ. Перевыставив купленное по
            # цене восстановления, ты встаёшь ЗА теми, кто уже стоит по
            # этой цене. Раньше здесь делилось только своё количество, и
            # метрика обещала «разойдётся за 3 часа» там, где впереди
            # стояла стена на 210 тысяч единиц. Карен проверил это
            # золотом: выкупил хвост «Сущности маназмея», перевыставил и
            # продал 19 штук.
            view.hours_to_clear = round(
                (view.wall_qty + view.deal_qty) / view.net_per_hour, 1
            )

        if view.points >= MIN_POINTS:
            view.percentile = _percentile(history["market"], market)
            first = float(history["market"].iloc[0])
            if first:
                view.change_pct = round((market / first - 1) * 100, 1)
            first_qty = float(history["quantity"].iloc[0])
            if first_qty:
                view.supply_change_pct = round((quantity / first_qty - 1) * 100, 1)

        _plan(view, book, market)
        # ОЧЕРЕДЬ МЕРЯЕТСЯ ОТ ТОГО, ЧТО ТЫ БЕРЁШЬ, а не от всего хвоста —
        # иначе предохранитель промахивается ровно там, где он нужнее
        # всего. Живой пример 2026-08-09: у «Кель'таласского филе» впереди
        # стояло 154 352 шт, но хвост был ещё больше, отношение выходило
        # меньше тройки, и товар спокойно попадал в находки первым номером.
        # Относительно реальной покупки очередь оказалась вчетверо длиннее.
        view.wall_ratio = (
            round(wall_qty / view.plan_qty, 1) if view.plan_qty else 0.0
        )
        _describe(view, event)
        views.append(view)

    return views


def _trusted(view: ItemView) -> bool:
    """Известно ли, что товар вообще расходится.

    Либо скорость измерена, либо это текущее дополнение, где спрос
    заведомо есть. Старьё без измерения — кот в мешке.
    """
    return view.hours_to_clear is not None or view.current_era


def bargains(views: list[ItemView], limit: int = 12) -> list[ItemView]:
    """Сделки, которые имеет смысл сделать прямо сейчас.

    ПОРЯДОК ПО ПРИБЫЛИ В ЧАС, А НЕ ПО РАЗМЕРУ НАВАРА. Это главная правка
    2026-08-09, и вот зачем она.

    Сортировка по абсолютному навару ставила наверх «Льняную ткань» с
    наваром 467 тысяч на 558 тысячах штук: арифметика верная, а выкупить
    столько льна и продать некому. Двухступенчатый порядок (сначала те,
    про кого известно, что расходятся) эту беду только притупил — внутри
    доверенных наверх всё равно лезло самое объёмное.

    Карен попробовал торговать по такому списку и описал результат точно:
    «пока ты их будешь продавать, появятся новые товары, которые перебьют
    тысячи наших; другие люди орудуют тысячей, а мы пытаемся сбыть сорок».
    Метрика сама вела туда, где застреваешь.

    Прибыль в час этого не допускает по устройству: она делится на срок
    сделки, поэтому сорок тысяч единиц, расходящихся неделю, проигрывают
    двум сотням, которые уйдут к вечеру.
    """
    worth = [
        v
        for v in views
        if v.plan_profit_gold >= MIN_UPSIDE_GOLD
        and v.plan_roi_pct >= MIN_ROI_PCT
        and v.lots >= 20
        # Стоячий рынок из списка действий выбрасываем: там нечего делать.
        # Из общей таблицы товар никуда не девается, со всеми своими
        # числами, — просто перестаёт выдавать себя за возможность.
        # Признак берём готовый (см. ItemView.stalled), а не пересчитываем:
        # копия этого условия здесь уже однажды разъехалась с оригиналом.
        and not v.stalled
    ]
    # Порядок: сначала те, про кого известно, что расходятся; внутри —
    # те, у кого разрыв ПОСТОЯНЕН, а не мелькнул однажды (маршрут, по
    # которому можно ходить каждый день, ценнее разовой удачи); и лишь
    # затем сама доходность — в час, а не в сумме.
    worth.sort(
        key=lambda v: (
            0 if _trusted(v) else 1,
            0 if (v.gap_rate or 0) >= 50 else 1,
            -v.plan_profit_per_hour,
        )
    )
    return worth[:limit]


# Недельный ритм: сколько суток истории нужно, чтобы вообще говорить, и
# сколько — чтобы говорить уверенно. Клеток в неделе 168, а снимков в
# сутки 24; за две недели на клетку приходится по два замера, за месяц —
# по четыре. Меньше двух недель — гадание.
RHYTHM_MIN_DAYS = 14
RHYTHM_RELIABLE_DAYS = 28

WEEKDAYS = ("Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс")


def _deviations(series: pd.Series) -> pd.Series:
    """Отклонение каждой точки от своего локального уровня, в процентах.

    Нормализация ОБЯЗАТЕЛЬНА, и это тот же урок, что на жетоне: без неё
    «ритм недели» выродился бы в «на этой неделе реагент подорожал».
    Особенно здесь, вокруг патча, где цены ездят в разы за дни.
    """
    if len(series) < 24:
        return pd.Series(dtype="float64")
    baseline = series.rolling("7D", center=True, min_periods=6).median()
    return ((series / baseline - 1) * 100).dropna()


def rhythm(
    region: str = config.PRIMARY_REGION, item_id: int | None = None, days: int = 60
) -> dict | None:
    """Внутринедельный рисунок цены: когда дешевле брать и когда дороже продавать.

    По ВРЕМЕНИ EU-СЕРВЕРОВ, а не по омскому: ритм создают ресеты и
    прайм-тайм, а живут они в серверном времени. Разница в четыре часа
    сдвинула бы картину на треть суток.

    Без item_id считается рынок ЦЕЛИКОМ: отклонения всех отслеживаемых
    товаров сводятся в один пул. Так ритм виден в разы раньше, чем по
    одному товару, — точек в 400 раз больше.

    ДЛЯ ЖЕТОНА ХВАТАЛО ОДНОЙ СТОРОНЫ, ЗДЕСЬ НУЖНЫ ОБЕ. Жетон Карен только
    покупает, поэтому там искали дно. Товары он и покупает, и продаёт —
    значит одинаково важны самый дешёвый час (брать) и самый дорогой
    (продавать запасённое).
    """
    table = frame(region)
    if table.empty:
        return None

    cutoff = table.index.max() - pd.Timedelta(days=days)
    table = table[table.index >= cutoff]
    if table.empty:
        return None

    span_days = (table.index.max() - table.index.min()).total_seconds() / 86400

    pool: list[pd.Series] = []
    items = [item_id] if item_id is not None else table["item_id"].unique().tolist()
    for one in items:
        chunk = table[table["item_id"] == one]
        if len(chunk) < 24:
            continue
        series = chunk["market"].astype(float)
        series = series[~series.index.duplicated(keep="last")]
        values = _deviations(series)
        if not values.empty:
            pool.append(values)

    if not pool:
        return None

    values = pd.concat(pool)
    local = values.tz_convert(config.SERVER_TZ)
    grid = pd.DataFrame(
        {
            "deviation": local.values,
            "weekday": local.index.weekday,
            "hour": local.index.hour,
        }
    )

    grouped = grid.groupby(["weekday", "hour"])["deviation"]
    means, sizes = grouped.mean(), grouped.size()

    cells = [
        {
            "weekday": WEEKDAYS[day],
            "hour": int(hour),
            "deviation": round(float(value), 2),
            "count": int(sizes[(day, hour)]),
        }
        for (day, hour), value in means.items()
        # Клетка на паре точек — шум, а не ритм.
        if sizes[(day, hour)] >= 4
    ]
    if not cells:
        return None

    ordered = sorted(cells, key=lambda c: c["deviation"])
    by_weekday = {
        WEEKDAYS[day]: round(float(value), 2)
        for day, value in grid.groupby("weekday")["deviation"].mean().items()
    }
    return {
        "item_id": item_id,
        "days": round(span_days, 1),
        "points": int(len(values)),
        "timezone": config.SERVER_TZ,
        "cheapest": ordered[:3],  # когда брать
        "dearest": ordered[-3:][::-1],  # когда продавать
        "by_weekday": by_weekday,
        "spread_pct": round(ordered[-1]["deviation"] - ordered[0]["deviation"], 2),
        "enough": span_days >= RHYTHM_MIN_DAYS,
        "reliable": span_days >= RHYTHM_RELIABLE_DAYS,
        "need_days": RHYTHM_MIN_DAYS,
    }


